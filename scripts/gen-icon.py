#!/usr/bin/env python3
"""Regenerate the launcher icon drawables from art/reedr.svg (512px pixel art made of <rect>s).

usage: scripts/gen-icon.py
"""
import os
import re

root = os.path.join(os.path.dirname(__file__), "..")
svg = open(os.path.join(root, "art/reedr.svg")).read()

by_color = {}
for attrs in re.findall(r"<rect ([^>]*)/>", svg):
    a = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
    color = a.get("fill", "").lower()
    if color == "white":
        continue  # the background; the adaptive icon has its own
    x, y, w, h = (float(a.get(k, 0)) for k in ("x", "y", "width", "height"))
    t = a.get("transform")
    if t:  # matrix(±1 0 0 ±1 tx ty): a flipped rect, as some editors export them
        sx, _, _, sy, tx, ty = map(float, re.findall(r"-?\d+(?:\.\d+)?", t))
        xs, ys = sorted([tx, tx + sx * w]), sorted([ty, ty + sy * h])
        x, w, y, h = xs[0], xs[1] - xs[0], ys[0], ys[1] - ys[0]
    by_color.setdefault(color, []).append(f"M{x:g},{y:g}h{w:g}v{h:g}h-{w:g}z")

# 512px art -> ART_DP inside the 108dp adaptive canvas (the safe circle is 66dp; smaller = more margin)
ART_DP = 52
S = ART_DP / 512
T = (108 - ART_DP) / 2


def doc(paths, comment):
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {comment} -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
        f'    <group android:translateX="{T}" android:translateY="{T}" android:scaleX="{S:.6f}" android:scaleY="{S:.6f}">',
    ]
    out += [f'        <path android:fillColor="{color}" android:pathData="{d}" />' for color, d in paths]
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


res = os.path.join(root, "app/src/main/res/drawable")
fg = [("@color/reedr_black", "".join(by_color["black"])), ("@color/reedr_blue", "".join(by_color["#0000ee"]))]
open(os.path.join(res, "ic_launcher_foreground.xml"), "w").write(
    doc(fg, "Generated from art/reedr.svg by scripts/gen-icon.py. Do not edit by hand."))
mono = [("#FFFFFFFF", "".join(by_color["black"]) + "".join(by_color["#0000ee"]))]
open(os.path.join(res, "ic_launcher_monochrome.xml"), "w").write(
    doc(mono, "Themed-icon version of art/reedr.svg (all ink in one colour). Generated by scripts/gen-icon.py."))
print({k: len(v) for k, v in by_color.items()})
